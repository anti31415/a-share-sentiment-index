"""
Self-contained HTML report for the seven-index ASI (indices.py output):
summary table, a year-to-date chart per index (smoothed ASI with the signal
bands, overheating days, state changes, and the index close), a generated
reading of each index, and the method notes.

    python asi/indices.py > /tmp/idx.json
    python asi/report_indices.py /tmp/idx.json /tmp/report.html [--labels labels.json]

All user-facing text comes from LABELS; --labels merges a JSON file of the
same shape over it, which is how a translated report is produced without
keeping translated text in this repository.
"""
