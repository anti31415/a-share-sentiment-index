def merged_labels(path):
    labels = json.loads(json.dumps(LABELS))
    if path:
        with open(path, encoding="utf-8") as f:
            extra = json.load(f)
        for k, v in extra.items():
            if isinstance(v, dict) and isinstance(labels.get(k), dict):
                labels[k].update(v)
            else:
                labels[k] = v
    return labels


def pct(x, nd=0):
    return "–" if x is None else ("%." + str(nd) + "f%%") % x


def esc(s):
    return html.escape(str(s))


def rarity_text(L, s):
    r = s["rarity"]
    return "%s · %s" % (L["side"][r["side"]], L["rarity"][r["label"] or "none"])


def odds_text(L, s, h):
    o = s["odds"].get(h) or {}
    if o.get("win_rate") is None:
        return L["na"]
    return "%s %s" % (L["odds_word"][s["odds"]["side"]], pct(o["win_rate"]))


def state_since(s):
    trans = s["transitions_ytd"]
    return trans[-1]["date"] if trans else None


# ------------------------------------------------------------------ chart
def chart(L, s, w=720, h=240):
    pts = s["ytd"]
    if len(pts) < 2:
        return ""
    pad_l, pad_r, pad_t, pad_b = 34, 46, 12, 26
    iw, ih = w - pad_l - pad_r, h - pad_t - pad_b
    n = len(pts)
    x = lambda i: pad_l + iw * i / (n - 1)
    y = lambda v: pad_t + ih * (1 - v / 100.0)
    closes = [p["close"] for p in pts]
    lo, hi = min(closes), max(closes)
    span = (hi - lo) or 1.0
    yc = lambda c: pad_t + ih * (1 - (c - lo) / span)
    out = ['<svg viewBox="0 0 %d %d" role="img" aria-label="%s">' % (w, h, esc(s["name"]))]
    out.append('<rect class="band-trim" x="%.1f" y="%.1f" width="%.1f" height="%.1f"/>' % (pad_l, y(75), iw, y(52) - y(75)))
    out.append('<rect class="band-buy" x="%.1f" y="%.1f" width="%.1f" height="%.1f"/>' % (pad_l, y(28), iw, y(0) - y(28)))
    for v in (0, 25, 50, 75, 100):
        out.append('<line class="grid" x1="%d" x2="%d" y1="%.1f" y2="%.1f"/>' % (pad_l, w - pad_r, y(v), y(v)))
        out.append('<text class="ax" x="%d" y="%.1f" text-anchor="end">%d</text>' % (pad_l - 6, y(v) + 4, v))
    for c in (lo, hi):
        out.append('<text class="ax" x="%d" y="%.1f">%s</text>' % (w - pad_r + 6, yc(c) + 4, "{:,.0f}".format(c)))
    last_m = None
    for i, p in enumerate(pts):
        m = p["date"][5:7]
        if m != last_m:
            out.append('<text class="ax" x="%.1f" y="%d" text-anchor="middle">%s</text>' % (x(i), h - 8, str(int(m)) + L.get("month_suffix", "")))
            last_m = m
    for i, p in enumerate(pts):
        if p["heat"] is not None and p["heat"] >= 0.9:
            out.append('<rect class="hot" x="%.1f" y="%d" width="%.1f" height="5"/>' % (x(i) - iw / n / 2, pad_t - 9, max(iw / n, 1.5)))
    out.append('<polyline class="close" points="%s"/>' % " ".join("%.1f,%.1f" % (x(i), yc(p["close"])) for i, p in enumerate(pts)))
    out.append('<polyline class="asi" points="%s"/>' % " ".join("%.1f,%.1f" % (x(i), y(p["asi_sm"])) for i, p in enumerate(pts)))
    idx = {p["date"]: i for i, p in enumerate(pts)}
    for t in s["transitions_ytd"]:
        i = idx.get(t["date"])
        if i is None:
            continue
        up = t["to"] in ("Ice-cold (full)", "Pessimistic (add)")
        dn = t["to"] == "Optimistic (trim)"
        cls = "chg-add" if up else ("chg-trim" if dn else "chg-neutral")
        out.append('<circle class="%s" cx="%.1f" cy="%.1f" r="4.5"><title>%s %s → %s</title></circle>' % (
            cls, x(i), y(pts[i]["asi_sm"]), esc(t["date"]), esc(L["states"].get(t["from"], t["from"])), esc(L["states"].get(t["to"], t["to"]))))
    i = n - 1
    out.append('<circle class="now" cx="%.1f" cy="%.1f" r="4"/>' % (x(i), y(pts[i]["asi_sm"])))
    out.append('<text class="nowlbl" x="%.1f" y="%.1f" text-anchor="end">%.1f</text>' % (x(i) - 7, y(pts[i]["asi_sm"]) - 7, pts[i]["asi_sm"]))
    out.append("</svg>")
    return "".join(out)


