def state_class(st):
    return {"Optimistic (trim)": "st-trim", "Pessimistic (add)": "st-add", "Ice-cold (full)": "st-add"}.get(st, "st-neutral")


def render(data, L):
    idx = data["indices"]
    prim = next((s for s in idx if s["primary"]), idx[0])
    o = ['<!doctype html><html lang="%s"><head><meta charset="utf-8">' % esc(L["lang"]),
         '<meta name="viewport" content="width=device-width,initial-scale=1">',
         '<title>%s</title>' % esc(L["title"]),
         '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;700&family=Noto+Serif+SC:wght@700&display=swap">',
         "<style>%s</style></head><body><div class=\"wrap\">" % CSS,
         "<h1>%s</h1>" % esc(L["title"]),
         '<div class="asof">%s</div>' % esc(L["as_of"].format(date=data["as_of"]))]
    o.append('<div class="headline"><p>%s</p>' % esc(L["headline_primary"].format(
        state=L["states"].get(prim["state"], prim["state"]), weight=pct(prim["satellite_target_weight"] * 100))))
    changes = [s for s in idx if s["triggered"]]
    if changes:
        items = "; ".join("%s %s → %s%s" % (s["name"], L["states"].get(s["prior_state"], s["prior_state"]),
                                             L["states"].get(s["state"], s["state"]),
                                             (" (" + L["reasons"][s["trigger_reason"]] + ")") if s["trigger_reason"] else "")
                          for s in changes)
        o.append("<p><b>%s</b></p>" % esc(L["headline_changes"].format(items=items)))
    else:
        o.append("<p>%s</p>" % esc(L["headline_quiet"]))
    missing = sorted({m for s in idx for m in s["missing_inputs"]})
    if missing:
        o.append('<p class="warn">%s</p>' % esc(L["headline_missing"].format(items=", ".join(missing))))
    o.append("</div>")

    o.append("<h2>%s</h2><div class=\"tbl\"><table><thead><tr>%s</tr></thead><tbody>" % (
        esc(L["table_title"]), "".join("<th>%s</th>" % esc(c) for c in L["cols"])))
    for s in idx:
        ch = s["change_pct"]
        o.append("<tr><td>%s%s</td><td>%s</td><td class=\"%s\">%+.2f%%</td><td>%.1f</td><td>%s</td>"
                 "<td><span class=\"pill %s\">%s</span></td><td>%s</td><td>%s</td><td>%s</td></tr>" % (
                     esc(s["name"]), ('<span class="tag">%s</span>' % esc(L["primary_tag"])) if s["primary"] else "",
                     "{:,.2f}".format(s["close"]), "up" if ch > 0 else ("down" if ch < 0 else ""), ch,
                     s["asi_smoothed_5d"], pct(s["heat"] * 100 if s["heat"] is not None else None),
                     state_class(s["state"]), esc(L["states"].get(s["state"], s["state"])),
                     esc(rarity_text(L, s)), esc(odds_text(L, s, "3m")), esc(odds_text(L, s, "6m"))))
    o.append("</tbody></table></div>")

    lg = L["legend"]
    o.append("<h2>%s</h2>" % esc(L["charts_title"]))
    o.append('<div class="legend"><span><i style="background:var(--accent)"></i>%s</span>'
             '<span><i style="background:var(--close)"></i>%s</span>'
             '<span><i style="background:var(--band-trim);border:1px solid var(--trim)"></i>%s</span>'
             '<span><i style="background:var(--band-buy);border:1px solid var(--add)"></i>%s</span>'
             '<span><i style="background:var(--hot)"></i>%s</span>'
             '<span><i style="background:var(--trim);border-radius:50%%;width:10px"></i>%s</span></div>' % tuple(
                 esc(lg[k]) for k in ("asi", "close", "trim_band", "buy_band", "hot", "change")))
    o.append('<div class="grid2">')
    for s in idx:
        since = state_since(s)
        o_ = s["odds"]
        reading = L["reading"].format(
            sm="%.1f" % s["asi_smoothed_5d"], side=L["side"][s["rarity"]["side"]],
            rarity=L["rarity"][s["rarity"]["label"] or "none"],
            heat=pct(s["heat"] * 100 if s["heat"] is not None else None),
            word=L["odds_word"][o_["side"]],
            p3=o_["3m"]["win_rate"] if o_["3m"]["win_rate"] is not None else L["na"],
            m3="%+.1f" % o_["3m"]["median_return"] if o_["3m"]["median_return"] is not None else L["na"],
            p6=o_["6m"]["win_rate"] if o_["6m"]["win_rate"] is not None else L["na"],
            m6="%+.1f" % o_["6m"]["median_return"] if o_["6m"]["median_return"] is not None else L["na"],
            ep=o_["episodes"], state=L["states"].get(s["state"], s["state"]),
            since=L["since"].format(date=since) if since else "")
        if s["state"] == "Optimistic (trim)" and s.get("trim_by"):
            reading += L["trim_by"][s["trim_by"]]
        if s["history_start"] > "2016-12-31":
            reading += L["short_history"].format(date=s["history_start"])
        o.append('<div class="card"><h3>%s%s <span class="num">%s &nbsp;%+.2f%%</span></h3>%s<p>%s</p></div>' % (
            esc(s["name"]), ('<span class="tag">%s</span>' % esc(L["primary_tag"])) if s["primary"] else "",
            "{:,.2f}".format(s["close"]), s["change_pct"], chart(L, s), esc(reading)))
    o.append("</div>")

    o.append("<h2>%s</h2><div class=\"method\">" % esc(L["method_title"]))
    for block in L["method"]:
        if isinstance(block, dict):
            o.append("<h4>%s</h4>" % esc(block["h"]))
            if block.get("items"):
                o.append("<ul>%s</ul>" % "".join("<li>%s</li>" % esc(i) for i in block["items"]))
            if block.get("p"):
                o.append("<p>%s</p>" % esc(block["p"]))
        else:
            o.append("<p>%s</p>" % esc(block))
    o.append("</div><footer>%s</footer></div></body></html>" % esc(L["footer"]))
    return "\n".join(o)


if __name__ == "__main__":
    args = sys.argv[1:]
    labels_path = None
    if "--labels" in args:
        i = args.index("--labels")
        labels_path = args[i + 1]
        args = args[:i] + args[i + 2:]
    with open(args[0], encoding="utf-8") as f:
        data = json.load(f)
    L = merged_labels(labels_path)
    names = L.get("index_names", {})
    for s in data["indices"]:
        s["name"] = names.get(s["symbol"], s["name"])
    with open(args[1], "w", encoding="utf-8") as f:
        f.write(render(data, L))
